"""
OAuth Session Service.

Manages browser sessions for cross-app user identification.
Sessions are stored in the database and referenced by a cookie token.

Security:
- Session tokens are hashed (SHA-256) before storage for O(1) indexed lookup
- Session tokens are encrypted (Fernet) for audit/recovery
- Lookup is by hash, never by plaintext token
- Plaintext tokens are never stored in the database
"""

import re
import secrets
from datetime import datetime, timedelta, timezone
from uuid import UUID

from sqlalchemy import delete, select, update
from sqlalchemy.ext.asyncio import AsyncSession

from backend.core.encryption import encrypt_token, hash_token
from backend.core.logging import get_logger
from backend.core.oauth_provider.models import OAuthSession

logger = get_logger(__name__)

# Session configuration
SESSION_TOKEN_BYTES = 32  # 32 bytes = 64 hex characters
SESSION_LIFETIME_DAYS = 30  # 30 days — reduced from 2 years to limit shared-device leakage window


def _generate_session_token() -> str:
    """
    Generate a cryptographically secure session token.

    Returns:
        64-character hex string (32 bytes)
    """
    return secrets.token_hex(SESSION_TOKEN_BYTES)


async def create_session(
    user_id: UUID | str,
    db: AsyncSession,
    correlation_id: str | None = None,
) -> str:
    """
    Create a new session for a user.

    Security:
    - Stores SHA-256 hash for indexed lookup
    - Stores Fernet-encrypted token for audit/recovery
    - Plaintext token is returned but never stored

    Args:
        user_id: User's UUID
        db: Database session
        correlation_id: Request correlation ID for logging

    Returns:
        Session token (64-char hex string) to store in cookie
    """
    request_logger = logger.bind(correlation_id=correlation_id)

    # Ensure user_id is a UUID
    if isinstance(user_id, str):
        user_id = UUID(user_id)

    # Generate unique session token
    session_token = _generate_session_token()

    # Hash and encrypt for secure storage (Increment 20)
    session_token_hash = hash_token(session_token)
    session_token_enc = encrypt_token(session_token)

    # Calculate expiration (730 days from now)
    expires_at = datetime.now(timezone.utc) + timedelta(days=SESSION_LIFETIME_DAYS)

    # Create session record
    session = OAuthSession(
        user_id=user_id,
        session_token_hash=session_token_hash,
        session_token_enc=session_token_enc,
        expires_at=expires_at,
    )

    db.add(session)
    await db.commit()

    request_logger.info(
        "oauth.session.created",
        user_id=str(user_id),
        expires_at=expires_at.isoformat(),
    )

    return session_token


async def get_session_user(
    token: str,
    db: AsyncSession,
    correlation_id: str | None = None,
) -> UUID | None:
    """
    Look up user by session token and extend session expiry.

    Implements sliding window expiration: each successful lookup
    extends the session by SESSION_LIFETIME_DAYS (30 days).

    Security:
    - Looks up by session_token_hash (indexed) instead of plaintext
    - Plaintext tokens are never stored

    Args:
        token: Session token from cookie
        db: Database session
        correlation_id: Request correlation ID for logging

    Returns:
        User's UUID if session is valid and not expired, None otherwise
    """
    request_logger = logger.bind(correlation_id=correlation_id)

    # Type guard: token must be a 64-char lowercase hex string (generated by secrets.token_hex(32))
    if not isinstance(token, str) or not re.fullmatch(r"[0-9a-f]{64}", token):
        return None

    # Hash the token for lookup (Increment 20)
    token_hash = hash_token(token)

    # Look up session by hash (indexed)
    result = await db.execute(
        select(OAuthSession).where(OAuthSession.session_token_hash == token_hash)
    )
    session = result.scalar_one_or_none()

    if not session:
        request_logger.debug("oauth.session.not_found")
        return None

    # Check expiration
    now = datetime.now(timezone.utc)
    if session.expires_at < now:
        request_logger.debug(
            "oauth.session.expired",
            user_id=str(session.user_id),
            expired_at=session.expires_at.isoformat(),
        )
        return None

    # Extend expiration (sliding window)
    new_expires_at = now + timedelta(days=SESSION_LIFETIME_DAYS)

    await db.execute(
        update(OAuthSession)
        .where(OAuthSession.id == session.id)
        .values(expires_at=new_expires_at)
    )
    await db.commit()

    request_logger.debug(
        "oauth.session.extended",
        user_id=str(session.user_id),
        new_expires_at=new_expires_at.isoformat(),
    )

    return session.user_id


async def delete_session(
    token: str,
    db: AsyncSession,
    correlation_id: str | None = None,
) -> bool:
    """
    Delete a session by token.

    Security:
    - Deletes by session_token_hash (indexed)
    - Plaintext tokens are never stored

    Args:
        token: Session token from cookie
        db: Database session
        correlation_id: Request correlation ID for logging

    Returns:
        True if session was deleted, False if not found
    """
    request_logger = logger.bind(correlation_id=correlation_id)

    # Type guard: token must be a 64-char lowercase hex string (generated by secrets.token_hex(32))
    if not isinstance(token, str) or not re.fullmatch(r"[0-9a-f]{64}", token):
        return False

    # Hash the token for lookup (Increment 20)
    token_hash = hash_token(token)

    # Delete by hash (indexed)
    result = await db.execute(
        delete(OAuthSession).where(OAuthSession.session_token_hash == token_hash)
    )

    await db.commit()

    deleted = result.rowcount > 0

    # Log with token prefix for debugging (first 8 chars is safe to log)
    token_prefix = token[:8]

    if deleted:
        request_logger.info("oauth.session.deleted", token_prefix=token_prefix)
    else:
        request_logger.debug("oauth.session.delete_not_found", token_prefix=token_prefix)

    return deleted


async def delete_user_sessions(
    user_id: UUID | str,
    db: AsyncSession,
    correlation_id: str | None = None,
) -> int:
    """
    Delete all sessions for a user (for full data deletion).

    Call this when deleting a user to prevent orphaned session tokens.
    Also remember to call delete_session_cookie() on the response.

    Args:
        user_id: User's UUID
        db: Database session
        correlation_id: Request correlation ID for logging

    Returns:
        Number of sessions deleted
    """
    request_logger = logger.bind(correlation_id=correlation_id)

    if isinstance(user_id, str):
        user_id = UUID(user_id)

    result = await db.execute(
        delete(OAuthSession).where(OAuthSession.user_id == user_id)
    )
    await db.commit()

    deleted_count = result.rowcount

    request_logger.info(
        "oauth.session.user_sessions_deleted",
        user_id=str(user_id),
        deleted_count=deleted_count,
    )

    return deleted_count


async def cleanup_expired_sessions(
    db: AsyncSession,
    correlation_id: str | None = None,
) -> int:
    """
    Delete all expired sessions.

    Called by Celery cleanup task.

    Args:
        db: Database session
        correlation_id: Request correlation ID for logging

    Returns:
        Number of sessions deleted
    """
    request_logger = logger.bind(correlation_id=correlation_id)

    now = datetime.now(timezone.utc)

    result = await db.execute(
        delete(OAuthSession).where(OAuthSession.expires_at < now)
    )
    await db.commit()

    deleted_count = result.rowcount

    request_logger.info(
        "oauth.session.cleanup_complete",
        deleted_count=deleted_count,
    )

    return deleted_count
